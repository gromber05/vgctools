export function effectiveness(attack: string, defTypes: string[], ability = ''): number {
  let m = 1;
  for (const d of defTypes) m *= CHART[attack]?.[d] ?? 1;
  const a = ABILITY_DEFENSE[ability]?.[attack];
  if (a !== undefined) m = a === 0 ? 0 : m * a;
  return m;
}
